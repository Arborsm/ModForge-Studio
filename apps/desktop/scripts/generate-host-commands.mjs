import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const desktopRoot = resolve(__dirname, '..')
const srcTauriDir = resolve(desktopRoot, 'src-tauri/src')
const outputPath = resolve(desktopRoot, 'src/platform/host-commands/index.ts')
const libRsPath = resolve(srcTauriDir, 'lib.rs')
const sidecarPath = resolve(srcTauriDir, 'host/sidecar.rs')

/** Marker placed at the top of every generated block; keep in sync with architecture tests. */
export const GENERATED_HEADER = '// Generated by apps/desktop/scripts/generate-host-commands.mjs. Do not edit by hand.'

/** Continuation indent of `.invoke_handler(tauri::generate_handler![ ... ])` in lib.rs. */
const RUST_BLOCK_INDENT = '            '

function toCamelCase(value) {
  return value.replace(/_([a-z0-9])/g, (_, char) => char.toUpperCase())
}

/**
 * Locale-independent string ordering (UTF-16 code units). `localeCompare`
 * without an explicit locale depends on the host's locale settings, which
 * makes the generated blocks order differently across machines and trips the
 * byte-exact lib.rs drift comparison in build.rs.
 */
function compareStrings(left, right) {
  return left < right ? -1 : left > right ? 1 : 0
}

/**
 * Extracts host command declarations from a commands source file. Two forms
 * are recognized:
 *
 * - macro form: `#[host_command(...)] pub async fn name(app: AppHandle, ...)`
 *   — the envelope struct/impl/wrapper are generated by the proc-macro, so
 *   the params type is derived from the function name and no struct-level
 *   drift validation is possible or needed (compile-time enforced).
 * - hand-written typed form: `#[tauri::command] pub async fn ...` ending in
 *   `runtime::execute(app, <Params> { .. }).await` — the struct/NAME/serde
 *   drift is verified by `validateTypedBinding`.
 *
 * Every attribute occurrence must yield a command: the strict patterns only
 * accept `pub (async) fn <snake_case_name>(...)`, and any attribute whose
 * following function does not match throws instead of being silently skipped
 * — a skipped command would compile (the macro accepts any name) but never
 * reach `generate_handler!`, `HOST_COMMANDS` or the sidecar routing table.
 */
export function extractCommands(source, filePath = '<source>') {
  const commands = []

  const fnPattern = /^\s*pub\s+(?:async\s+)?fn\s+([a-z][a-z0-9_]*)\s*\(([^)]*)\)/

  const macroAttrPattern = /#\[host_command\([^\]]*\)\]/g
  for (const attrMatch of source.matchAll(macroAttrPattern)) {
    if (source.lastIndexOf('//', attrMatch.index) > source.lastIndexOf('\n', attrMatch.index)) {
      continue
    }
    const fnMatch = fnPattern.exec(source.slice(attrMatch.index + attrMatch[0].length))
    if (!fnMatch) {
      throw new Error(
        `#[host_command(...)] in ${filePath} at offset ${attrMatch.index} must be followed by \`pub async fn <name>(app: AppHandle, ...)\` with a snake_case name matching [a-z][a-z0-9_]*; anything else is silently unreachable from the frontend and sidecar`,
      )
    }
    const wireName = fnMatch[1]
    commands.push({
      wireName,
      tsName: toCamelCase(wireName),
      kind: 'macro',
      typed: { paramsType: `${toPascalCase(wireName)}Params`, argNames: parsePayloadArgNames(fnMatch[2], wireName) },
    })
  }

  const manualAttrPattern = /#\[tauri::command\]/g
  const findBody = (fromIndex) => {
    const open = source.indexOf('{', fromIndex)
    if (open < 0) {
      throw new Error('Command body is missing its opening brace')
    }
    let depth = 0
    for (let index = open; index < source.length; index += 1) {
      const character = source[index]
      if (character === '{') {
        depth += 1
      } else if (character === '}') {
        depth -= 1
        if (depth === 0) {
          return source.slice(open + 1, index)
        }
      }
    }
    throw new Error('Command body is missing its closing brace')
  }

  for (const attrMatch of source.matchAll(manualAttrPattern)) {
    if (source.lastIndexOf('//', attrMatch.index) > source.lastIndexOf('\n', attrMatch.index)) {
      continue
    }
    const fnMatch = fnPattern.exec(source.slice(attrMatch.index + attrMatch[0].length))
    if (!fnMatch) {
      throw new Error(
        `#[tauri::command] in ${filePath} at offset ${attrMatch.index} must be followed by \`pub async fn <name>(app: AppHandle, ...)\` with a snake_case name matching [a-z][a-z0-9_]*`,
      )
    }
    const wireName = fnMatch[1]
    const params = fnMatch[2]
    const body = findBody(attrMatch.index + attrMatch[0].length + fnMatch[0].length)
    if (params.includes('State<')) {
      throw new Error(
        `Command ${wireName} must use the typed binding: (app: AppHandle, <payload args>) ending in runtime::execute(app, <Params> { .. }).await`,
      )
    }

    const executeCall = /runtime::execute\(\s*app\s*,\s*([A-Z][A-Za-z0-9_]*)\s*\{([^}]*)\}\s*,?\s*\)\s*\.await/.exec(body)
    if (!executeCall) {
      throw new Error(`Typed command ${wireName} must end with runtime::execute(app, <Params> { .. }).await`)
    }
    const initEntries = executeCall[2]
      .split(',')
      .map((segment) => segment.trim())
      .filter(Boolean)
    for (const entry of initEntries) {
      if (!/^[a-z][a-z0-9_]*$/.test(entry)) {
        throw new Error(`Typed command ${wireName} must construct <Params> with shorthand field inits, found ${entry}`)
      }
    }

    commands.push({
      wireName,
      tsName: toCamelCase(wireName),
      kind: 'manual',
      typed: { paramsType: executeCall[1], argNames: parsePayloadArgNames(params, wireName) },
    })
  }

  return commands
}

/** Splits a wrapper parameter list and returns the payload arg names (everything after `app`). */
function parsePayloadArgNames(params, wireName) {
  return params
    .split(',')
    .map((segment) => segment.trim())
    .filter((segment) => segment.length > 0 && !/^app\s*:/.test(segment))
    .map((segment) => {
      const name = /^([a-z][a-z0-9_]*)\s*:/.exec(segment)?.[1]
      if (!name) {
        throw new Error(`Typed command ${wireName} has an unparsable payload parameter: ${segment}`)
      }
      return name
    })
}

/** snake_case → PascalCase; must stay identical to the proc-macro's `to_pascal_case`. */
export function toPascalCase(value) {
  let out = ''
  let capitalize = true
  for (const character of value) {
    if (character === '_') {
      capitalize = true
    } else if (capitalize) {
      out += character.toUpperCase()
      capitalize = false
    } else {
      out += character
    }
  }
  return out
}

/**
 * Validates a typed binding within its source file: the params struct must
 * declare the camelCase wire contract once, its fields must equal the wrapper
 * payload arguments (Tauri derives its keys from arg names, the sidecar from
 * struct fields, so equality pins both), `Option` fields must be
 * `#[serde(default)]` and only those, and the `HostCommand` impl must
 * declare `NAME` equal to the wrapper function name.
 */
export function validateTypedBinding(source, command) {
  const { wireName, typed } = command
  const structPattern = /pub struct\s+([A-Za-z][A-Za-z0-9_]*)\s*\{([\s\S]*?)\n\}/g
  const structs = new Map()
  for (const match of source.matchAll(structPattern)) {
    structs.set(match[1], { body: match[2], start: match.index })
  }
  const struct = structs.get(typed.paramsType)
  if (!struct) {
    throw new Error(`Typed command ${wireName} is missing its wire envelope struct ${typed.paramsType}`)
  }
  const before = source.slice(Math.max(0, struct.start - 120), struct.start)
  if (!before.includes('#[serde(rename_all = "camelCase")]')) {
    throw new Error(`${typed.paramsType} for ${wireName} must declare #[serde(rename_all = "camelCase")] once`)
  }

  const fields = []
  const fieldPattern = /(#\[serde\(default\)\]\s*\n\s*)?pub\s+([a-z][a-z0-9_]*)\s*:\s*([^,\n]+)/g
  for (const match of struct.body.matchAll(fieldPattern)) {
    fields.push({ name: match[2], type: match[3].trim(), defaulted: Boolean(match[1]) })
  }
  const fieldNames = fields.map((field) => field.name)
  const missing = typed.argNames.filter((name) => !fieldNames.includes(name))
  const extra = fieldNames.filter((name) => !typed.argNames.includes(name))
  if (missing.length > 0 || extra.length > 0) {
    throw new Error(
      `${typed.paramsType} fields must equal ${wireName} payload arguments (camelCase keys are derived from both): missing ${missing.join(', ') || 'none'}, extra ${extra.join(', ') || 'none'}`,
    )
  }
  for (const field of fields) {
    const optional = field.type.includes('Option<')
    if (optional !== field.defaulted) {
      throw new Error(`${typed.paramsType}.${field.name} for ${wireName} must ${optional ? 'carry' : 'not carry'} #[serde(default)]`)
    }
  }

  const implPattern = /impl\s+HostCommand\s+for\s+([A-Za-z][A-Za-z0-9_]*)\s*\{/g
  const impls = []
  for (const match of source.matchAll(implPattern)) {
    impls.push({ type: match[1], start: match.index })
  }
  const implIndex = impls.findIndex((impl) => impl.type === typed.paramsType)
  if (implIndex < 0) {
    throw new Error(`Typed command ${wireName} is missing impl HostCommand for ${typed.paramsType}`)
  }
  const impl = impls[implIndex]
  const nextImplStart = impls[implIndex + 1]?.start ?? source.length
  const nameMatch = /const NAME:\s*&'static str\s*=\s*"([a-z][a-z0-9_]*)"/.exec(source.slice(impl.start, nextImplStart))
  const declaredName = nameMatch?.[1]
  if (declaredName !== wireName) {
    throw new Error(
      `${typed.paramsType} for ${wireName} must declare const NAME: &'static str = "${wireName}", found ${declaredName ?? 'none'}`,
    )
  }
}

/**
 * Recursively scans every `commands.rs` under the Tauri src tree (the
 * bindings live next to their domain modules, e.g.
 * `domain/launcher/commands.rs`) for host commands. Each command is tagged
 * with its file's module path (e.g. `domain::launcher::commands`) and, for
 * hand-written bindings, its validated params type.
 */
export async function scanCommandFiles(srcTauriDirPath) {
  const commandFiles = []
  const walk = async (dir) => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const fullPath = resolve(dir, entry.name)
      if (entry.isDirectory()) {
        // Test helper files (e.g. src/tests/**/commands.rs) are not bindings
        // and would derive non-existent module paths.
        if (entry.name !== 'tests') {
          await walk(fullPath)
        }
      } else if (entry.name === 'commands.rs') {
        commandFiles.push(fullPath)
      }
    }
  }
  await walk(srcTauriDirPath)
  commandFiles.sort(compareStrings)

  const commands = []
  const seen = new Set()
  const seenTsNames = new Set()

  for (const filePath of commandFiles) {
    const source = await readFile(filePath, 'utf8')
    const modulePath = relative(srcTauriDirPath, filePath).replaceAll('\\', '/').replace(/\.rs$/, '').replaceAll('/', '::')
    for (const command of extractCommands(source, filePath)) {
      if (seen.has(command.wireName)) {
        throw new Error(`Duplicate host command function name: ${command.wireName}`)
      }
      if (seenTsNames.has(command.tsName)) {
        throw new Error(
          `HOST_COMMANDS key collision: '${command.tsName}' is derived from more than one wire name (${command.wireName} and another snake_case name that camel-cases identically)`,
        )
      }
      seen.add(command.wireName)
      seenTsNames.add(command.tsName)
      if (command.typed && command.kind !== 'macro') {
        validateTypedBinding(source, command)
      }
      commands.push({ ...command, module: modulePath })
    }
  }

  if (commands.length === 0) {
    throw new Error(`No host commands found under ${srcTauriDirPath}`)
  }

  return commands
}

export function renderHostCommands(commands) {
  const entries = commands.map((command) => `  ${command.tsName}: '${command.wireName}',`).join('\n')
  return `${GENERATED_HEADER}\n\n/** Host command protocol names generated from Tauri command function names. */\nexport const HOST_COMMANDS = {\n${entries}\n} as const\n\nexport type HostCommandName = (typeof HOST_COMMANDS)[keyof typeof HOST_COMMANDS]\n`
}

/**
 * Renders the body of the `.invoke_handler(tauri::generate_handler![ ... ])` block in lib.rs,
 * grouped by module (one full path per command).
 */
export function renderRustHandlerBlock(commands) {
  const byModule = new Map()
  for (const command of commands) {
    const group = byModule.get(command.module) ?? []
    group.push(command.wireName)
    byModule.set(command.module, group)
  }

  const lines = [`${RUST_BLOCK_INDENT}${GENERATED_HEADER}`]
  for (const module of [...byModule.keys()].sort(compareStrings)) {
    lines.push(`${RUST_BLOCK_INDENT}// ${module}`)
    for (const wireName of byModule.get(module).sort()) {
      lines.push(`${RUST_BLOCK_INDENT}${module}::${wireName},`)
    }
  }
  return lines.join('\n')
}

/** Extracts every `host_command_wire!(name)` dispatch arm declared in sidecar.rs. */
export function extractSidecarWireNames(source) {
  const names = []
  for (const match of source.matchAll(/host_command_wire!\(([a-z][a-z0-9_]*)\)/g)) {
    names.push(match[1])
  }
  return names
}

/**
 * Extracts typed dispatch arms:
 * `host_command_wire!(name) => { resolve_typed::<crate::<module::path>::Type>(ctx, id, args) }`
 * (whitespace-insensitive; accepts every rustfmt layout, including wrapped
 * generics and wrapped call arguments). The module path may span several
 * segments (e.g. `domain::launcher::commands`).
 */
export function extractTypedSidecarArms(source) {
  const arms = new Map()
  const pattern =
    /crate::host_command_wire!\(([a-z][a-z0-9_]*)\)\s*=>\s*\{?\s*resolve_typed::<\s*crate::([a-z][a-z0-9_]*(?:::[a-z][a-z0-9_]*)*)::([A-Za-z][A-Za-z0-9_]*)\s*,?\s*>\s*\(\s*ctx\s*,\s*id\s*,\s*args\s*,?\s*\)\s*\}?\s*,?/g
  for (const match of source.matchAll(pattern)) {
    arms.set(match[1], { module: match[2], paramsType: match[3] })
  }
  return arms
}

/**
 * Ensures sidecar.rs declares exactly the canonical typed dispatch arms for
 * the scanned commands: every command needs a policy-free
 * `resolve_typed::<crate::commands::<module>::<Type>>(ctx, id, args)` pointer
 * arm, and every arm must name a known command with the matching params type.
 */
export function validateSidecarDispatch(sidecarSource, commands) {
  const wireNames = extractSidecarWireNames(sidecarSource)
  const typedArms = extractTypedSidecarArms(sidecarSource)
  const expected = new Set(commands.map((command) => command.wireName))
  const problems = []
  const missing = []
  const nonCanonical = []

  for (const command of commands) {
    const arm = typedArms.get(command.wireName)
    if (!arm) {
      if (wireNames.includes(command.wireName)) {
        nonCanonical.push(command.wireName)
      } else {
        missing.push(command.wireName)
      }
      continue
    }
    if (arm.module !== command.module || arm.paramsType !== command.typed.paramsType) {
      problems.push(
        `sidecar.rs typed arm for ${command.wireName} must point at crate::${command.module}::${command.typed.paramsType}, found crate::${arm.module}::${arm.paramsType}`,
      )
    }
  }

  const compare = compareStrings
  if (missing.length > 0) {
    problems.push(`sidecar.rs is missing dispatch arm(s) for: ${missing.sort(compare).join(', ')}`)
  }
  if (nonCanonical.length > 0) {
    problems.push(
      `sidecar.rs arm(s) must be the canonical resolve_typed::<crate::<module::path>::<Type>>(ctx, id, args) pointer: ${nonCanonical.sort(compare).join(', ')}`,
    )
  }
  const extra = [...wireNames].filter((name) => !expected.has(name)).sort(compare)
  if (extra.length > 0) {
    problems.push(`sidecar.rs declares unknown dispatch arm(s): ${extra.join(', ')}`)
  }

  // The generated block is sorted by module then wire name; pin that order so
  // a manually reordered arm cannot hide an otherwise canonical arm.
  const expectedOrder = []
  const byModule = new Map()
  for (const command of commands) {
    const group = byModule.get(command.module) ?? []
    group.push(command)
    byModule.set(command.module, group)
  }
  for (const module of [...byModule.keys()].sort(compareStrings)) {
    for (const command of byModule.get(module).sort((left, right) => compareStrings(left.wireName, right.wireName))) {
      expectedOrder.push(command.wireName)
    }
  }
  const actualOrder = [...typedArms.keys()]
  if (JSON.stringify(actualOrder) !== JSON.stringify(expectedOrder)) {
    problems.push(`sidecar.rs dispatch arm order drifted: expected ${expectedOrder.join(', ')}, found ${actualOrder.join(', ')}`)
  }

  if (problems.length === 0) {
    return
  }
  throw new Error(`Host command sidecar dispatch is out of sync with #[tauri::command] functions.\n${problems.join('\n')}`)
}

/**
 * Renders the sidecar routing block: one canonical policy-free type pointer
 * arm per command, grouped by module like the lib.rs handler block. The
 * renderer emits one stable text form; rustfmt may rewrap individual arms, so
 * drift checks compare the block whitespace-insensitively (see the node and
 * architecture tests).
 */
export function renderSidecarDispatchBlock(commands) {
  const byModule = new Map()
  for (const command of commands) {
    const group = byModule.get(command.module) ?? []
    group.push(command)
    byModule.set(command.module, group)
  }
  const ARM_INDENT = '        '
  const lines = [`${ARM_INDENT}${GENERATED_HEADER}`]
  for (const module of [...byModule.keys()].sort(compareStrings)) {
    lines.push(`${ARM_INDENT}// ${module}`)
    for (const command of byModule.get(module).sort((left, right) => compareStrings(left.wireName, right.wireName))) {
      lines.push(`${ARM_INDENT}crate::host_command_wire!(${command.wireName}) => resolve_typed::<`)
      lines.push(`${ARM_INDENT}    crate::${module}::${command.typed.paramsType},`)
      lines.push(`${ARM_INDENT}>(ctx, id, args),`)
    }
  }
  return lines.join('\n')
}

/** Replaces the generated routing block inside sidecar.rs::resolve_command. */
export function regenerateSidecarDispatch(sidecarSource, commands) {
  const startMarker = '    match command.as_str() {\n'
  const endMarker = '        _ => ResolvedCommandOrResponse::Response(HostCommandResponse {'
  const start = sidecarSource.indexOf(startMarker)
  const end = sidecarSource.indexOf(endMarker)
  if (start < 0 || end < 0 || end <= start) {
    throw new Error('sidecar.rs does not contain the resolve_command routing match')
  }
  const block = renderSidecarDispatchBlock(commands)
  return sidecarSource.slice(0, start + startMarker.length) + block + '\n' + sidecarSource.slice(end)
}

/** Replaces the `generate_handler![...]` block body inside lib.rs with the generated one. */
export function regenerateLibRsHandler(libRsSource, commands) {
  const pattern = /\.invoke_handler\(tauri::generate_handler!\[[\s\S]*?\]\s*\)/
  if (!pattern.test(libRsSource)) {
    throw new Error('lib.rs does not contain a .invoke_handler(tauri::generate_handler![...]) block')
  }
  const block = renderRustHandlerBlock(commands)
  return libRsSource.replace(pattern, () => `.invoke_handler(tauri::generate_handler![\n${block}\n        ])`)
}

/**
 * Validates that the three generated outputs — the sidecar routing block,
 * the lib.rs `generate_handler!` list and the frontend `HOST_COMMANDS` table —
 * are in sync with the scanned commands. Returns the list of drift problems
 * (empty = in sync). `build.rs` runs this via `--check` so `cargo build`
 * fails on drift instead of silently shipping stale routing.
 */
export async function checkHostCommandDrift() {
  const commands = await scanCommandFiles(srcTauriDir)
  commands.sort((left, right) => compareStrings(left.wireName, right.wireName))
  const problems = []

  const sidecarSource = await readFile(sidecarPath, 'utf8')
  try {
    validateSidecarDispatch(sidecarSource, commands)
  } catch (error) {
    problems.push(error.message)
  }

  const libRsSource = await readFile(libRsPath, 'utf8')
  try {
    if (regenerateLibRsHandler(libRsSource, commands) !== libRsSource) {
      problems.push('lib.rs generate_handler! block drifted from the scanned commands')
    }
  } catch (error) {
    problems.push(error.message)
  }

  const hostCommands = await readFile(outputPath, 'utf8')
  if (hostCommands.replace(/\r\n/g, '\n') !== renderHostCommands(commands)) {
    problems.push('frontend HOST_COMMANDS table drifted from the scanned commands')
  }

  return problems
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  const commands = await scanCommandFiles(srcTauriDir)
  commands.sort((left, right) => compareStrings(left.wireName, right.wireName))

  if (process.argv.includes('--check')) {
    const problems = await checkHostCommandDrift()
    if (problems.length > 0) {
      console.error(
        `Host command outputs are out of sync. Run: vp run --filter @modforge/desktop gen:host-commands\n\n${problems.join('\n\n')}`,
      )
      process.exitCode = 1
    }
  } else {
    // Validate the sidecar dispatch before writing any generated output.
    const sidecarSource = await readFile(sidecarPath, 'utf8')
    validateSidecarDispatch(sidecarSource, commands)

    const libRsSource = await readFile(libRsPath, 'utf8')
    const nextLibRs = regenerateLibRsHandler(libRsSource, commands)
    const nextSidecar = regenerateSidecarDispatch(sidecarSource, commands)

    await writeFile(outputPath, renderHostCommands(commands))
    await writeFile(libRsPath, nextLibRs)
    await writeFile(sidecarPath, nextSidecar)
  }
}
