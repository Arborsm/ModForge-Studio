import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const desktopRoot = resolve(__dirname, '..')
const commandsDir = resolve(desktopRoot, 'src-tauri/src/commands')
const outputPath = resolve(desktopRoot, 'src/platform/host-commands/index.ts')

function toCamelCase(value) {
  return value.replace(/_([a-z0-9])/g, (_, char) => char.toUpperCase())
}

function extractCommands(source) {
  const commands = []
  const pattern = /#\[tauri::command\]\s*pub\s+(?:async\s+)?fn\s+([a-z][a-z0-9_]*)/g

  for (const match of source.matchAll(pattern)) {
    const wireName = match[1]
    commands.push({
      wireName,
      tsName: toCamelCase(wireName),
    })
  }

  return commands
}

export function renderHostCommands(commands) {
  const entries = commands.map((command) => `  ${command.tsName}: '${command.wireName}',`).join('\n')
  return `// Generated by apps/desktop/scripts/generate-host-commands.mjs. Do not edit by hand.\n\n/** Host command protocol names generated from Tauri command function names. */\nexport const HOST_COMMANDS = {\n${entries}\n} as const\n\nexport type HostCommandName = (typeof HOST_COMMANDS)[keyof typeof HOST_COMMANDS]\n`
}

const commandFiles = (await readdir(commandsDir)).filter((fileName) => fileName.endsWith('.rs') && fileName !== 'runtime.rs').sort()
const commands = []
const seen = new Set()

for (const fileName of commandFiles) {
  const source = await readFile(resolve(commandsDir, fileName), 'utf8')
  for (const command of extractCommands(source)) {
    if (seen.has(command.wireName)) {
      throw new Error(`Duplicate host command function name: ${command.wireName}`)
    }
    seen.add(command.wireName)
    commands.push(command)
  }
}

if (commands.length === 0) {
  throw new Error(`No Tauri host commands found in ${commandsDir}`)
}

commands.sort((left, right) => left.wireName.localeCompare(right.wireName))
await writeFile(outputPath, renderHostCommands(commands))
