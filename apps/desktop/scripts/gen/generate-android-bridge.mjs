import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const desktopRoot = resolve(__dirname, '../..')
const repoRoot = resolve(desktopRoot, '../..')
const launcherManifestPath = resolve(repoRoot, 'shared/protocol/launcher-commands.json')
/** Default output lands in the modforge-android checkout next to this repository. */
const defaultOutputPath = resolve(repoRoot, '../modforge-android/SMAPIGameLoader/Bridge/Generated/LauncherBridge.g.cs')

const GENERATED_HEADER =
  '// Generated by apps/desktop/scripts/gen/generate-android-bridge.mjs from shared/protocol/launcher-commands.json. Do not edit by hand.'

/** snake_case → PascalCase; mirrors the Rust proc-macro's Params derivation. */
export function toPascalCase(value) {
  let out = ''
  let capitalize = true
  for (const character of value) {
    if (character === '_') {
      capitalize = true
    } else if (capitalize) {
      out += character.toUpperCase()
      capitalize = false
    } else {
      out += character
    }
  }
  return out
}

/** camelCase wire key → PascalCase C# property name. */
export function toPascalFromCamel(value) {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

/**
 * Maps a TypeScript type expression from the manifest onto the C# envelope
 * property type. Scalar wire args get real CLR types; every structured arg
 * travels as a `JsonElement?` that the service layer parses with its own
 * source-generated models.
 */
export function csharpArgType(typeExpression) {
  const normalized = typeExpression.trim()
  if (normalized === 'string') return 'string'
  if (normalized === 'boolean') return 'bool'
  if (normalized === 'number') return 'double'
  return 'global::System.Text.Json.JsonElement?'
}

/** Property initializer expression used inside dispatch arms for one payload arg. */
function csharpArgPass(typeExpression, propertyName) {
  if (csharpArgType(typeExpression) === 'global::System.Text.Json.JsonElement?') {
    return `Require(envelope.${propertyName}, command, "${propertyName.toLowerCase()}")`
  }
  return `envelope.${propertyName}`
}

/**
 * Renders the C# bridge source: one envelope record per command, the
 * source-generated serializer context for them, and the dispatch switch that
 * hands parsed payloads to `LauncherCommandServices`. Commands without an
 * `android` mapping in the manifest are intentionally left out of the switch —
 * the default arm reports them as unavailable on Android.
 */
export function renderAndroidBridge(manifest) {
  const commands = manifest.commands
  if (!Array.isArray(commands) || commands.length === 0) {
    throw new Error('launcher-commands.json must contain a non-empty "commands" array')
  }

  const lines = []
  lines.push(GENERATED_HEADER)
  lines.push('')
  lines.push('#nullable enable')
  lines.push('')
  lines.push('using System.Text.Json;')
  lines.push('using System.Text.Json.Serialization;')
  lines.push('using SMAPIGameLoader.Services;')
  lines.push('')
  lines.push('namespace SMAPIGameLoader.Bridge;')
  lines.push('')
  lines.push('/// <summary>')
  lines.push('/// Protocol envelope + dispatch for launcher host commands transported over the')
  lines.push('/// ModForgeBridge JS interface. The command set mirrors the desktop launcher')
  lines.push('/// domain; commands without an Android implementation answer through the')
  lines.push('/// default arm as unavailable.')
  lines.push('/// </summary>')
  lines.push('public static class LauncherBridgeGenerated')
  lines.push('{')
  lines.push('    public static async Task<object?> DispatchAsync(string command, JsonElement args, LauncherCommandServices services)')
  lines.push('    {')
  lines.push('        switch (command)')
  lines.push('        {')
  for (const entry of commands) {
    if (!entry.android) continue
    const paramsType = `${toPascalCase(entry.name)}Params`
    const argEntries = Object.entries(entry.params ?? {})
    if (argEntries.length === 0) {
      lines.push(`            case "${entry.name}":`)
      lines.push(`                return await services.${entry.android.service}.${entry.android.method}().ConfigureAwait(false);`)
    } else {
      lines.push(`            case "${entry.name}":`)
      lines.push('            {')
      lines.push(`                var envelope = Deserialize(args, LauncherBridgeJsonContext.Default.${paramsType});`)
      const argExpressions = argEntries.map(([argName, typeExpression]) => csharpArgPass(typeExpression, toPascalFromCamel(argName)))
      lines.push(
        `                return await services.${entry.android.service}.${entry.android.method}(${argExpressions.join(', ')}).ConfigureAwait(false);`,
      )
      lines.push('            }')
    }
  }
  lines.push('            default:')
  lines.push('                throw new LauncherCommandUnavailableException(command);')
  lines.push('        }')
  lines.push('    }')
  lines.push('')
  lines.push('    private static T Deserialize<T>(JsonElement args, JsonTypeInfo<T> typeInfo) where T : class')
  lines.push('    {')
  lines.push('        return JsonSerializer.Deserialize(args.Clone(), typeInfo)')
  lines.push('            ?? throw new LauncherCommandException("invalid_args", "Launcher command args envelope was null.");')
  lines.push('    }')
  lines.push('')
  lines.push('    private static JsonElement Require(JsonElement? value, string command, string argName)')
  lines.push('    {')
  lines.push('        if (value is not { } element || element.ValueKind == JsonValueKind.Undefined)')
  lines.push('        {')
  lines.push(
    '            throw new LauncherCommandException("invalid_args", $"Launcher command \\"{command}\\" is missing payload \\"{argName}\\".");',
  )
  lines.push('        }')
  lines.push('')
  lines.push('        return element;')
  lines.push('    }')
  lines.push('}')

  for (const entry of commands) {
    const paramsType = `${toPascalCase(entry.name)}Params`
    const argEntries = Object.entries(entry.params ?? {})
    lines.push('')
    if (argEntries.length === 0) {
      lines.push(`public sealed record ${paramsType}();`)
      continue
    }
    const properties = argEntries.map(([argName, typeExpression]) => {
      const type = csharpArgType(typeExpression)
      return `[property: JsonPropertyName("${argName}")] ${type} ${toPascalFromCamel(argName)}`
    })
    lines.push(`public sealed record ${paramsType}(${properties.join(', ')});`)
  }

  lines.push('')
  lines.push('/// <summary>Source-generated serializer set for the command envelopes above.</summary>')
  lines.push('[JsonSourceGenerationOptions(GenerationMode = JsonSourceGenerationMode.Metadata)]')
  for (const entry of commands) {
    lines.push(`[JsonSerializable(typeof(${toPascalCase(entry.name)}Params))]`)
  }
  lines.push('internal sealed partial class LauncherBridgeJsonContext : JsonSerializerContext')
  lines.push('{')
  lines.push('}')
  lines.push('')

  return `${lines.join('\n')}\n`
}

async function loadManifest() {
  return JSON.parse(await readFile(launcherManifestPath, 'utf8'))
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  const outIndex = process.argv.indexOf('--out')
  const outputPath = outIndex >= 0 ? resolve(process.cwd(), process.argv[outIndex + 1]) : defaultOutputPath
  const rendered = renderAndroidBridge(await loadManifest())

  if (process.argv.includes('--check')) {
    let existing = null
    try {
      existing = await readFile(outputPath, 'utf8')
    } catch {
      existing = null
    }
    if (existing !== rendered) {
      console.error(
        `Android bridge source is out of sync with ${launcherManifestPath}.\nRun: vp run --filter @modforge/desktop gen:android-bridge`,
      )
      process.exitCode = 1
    }
  } else {
    await mkdir(dirname(outputPath), { recursive: true })
    await writeFile(outputPath, rendered)
    console.log(`Wrote ${outputPath} (${rendered.length} bytes)`)
  }
}
